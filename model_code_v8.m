function code = fault_injector_body()
code = [ ...
"function [Ia,Ib,Ic,Va,Vb,Vc,fault_flag,G,A,B,C,reclose] = fault_injector(VaIn,VbIn,VcIn,t,FaultG,FaultA,FaultB,FaultC,MechanismCode,Severity,RampDuration,FaultOnsetTime,FaultDuration,SourceL,ReclosDelay,BreakerOpen)" newline ...
"%#codegen" newline ...
"persistent I_s I_src faultSamples initialized" newline ...
"if isempty(initialized)" newline ...
"    I_s = zeros(3,1); I_src = zeros(3,1); faultSamples = 0; initialized = true;" newline ...
"end" newline ...
"Ts = 1e-4; L = 0.02; R_normal = 5; R_source = 0.5;" newline ...
"% Source inductance as a backward-Euler equivalent resistance: Ls*(Iline[k]-Iline[k-1])/Ts = Vs - Rs*Iline[k] - Vt" newline ...
"Lr = SourceL / Ts; W = R_source + Lr;" newline ...
"fault_active = (t >= FaultOnsetTime) && (t < FaultOnsetTime + FaultDuration);" newline ...
"if fault_active, faultSamples = faultSamples + 1; else, faultSamples = 0; end" newline ...
"rampSamples = max(1, round(RampDuration / Ts)); frac = min(1, faultSamples / rampSamples);" newline ...
"flt = [double(FaultA); double(FaultB); double(FaultC)] > 0.5;" newline ...
"% 1. Source voltages and per-phase load resistance (mechanisms 3-6 act on one phase independently)" newline ...
"V_s = [VaIn; VbIn; VcIn];" newline ...
"R_load = [R_normal; R_normal; R_normal];" newline ...
"open_ph = false(3,1); R_open = R_normal;" newline ...
"if fault_active" newline ...
"    if MechanismCode == 3" newline ...
"        R_load(flt) = R_normal + frac * (Severity - R_normal);" newline ...
"    elseif MechanismCode == 4 || MechanismCode == 5" newline ...
"        V_s(flt) = V_s(flt) * (1 + frac * (Severity - 1));" newline ...
"    elseif MechanismCode == 6" newline ...
"        open_ph = flt; R_open = R_normal + frac * (Severity - R_normal);" newline ...
"    end" newline ...
"end" newline ...
"% 2. Fault admittance matrix at the terminal bus (short circuits only, mechanism 2)" newline ...
"%    LG / LLG / LLLG: Severity ohm from each faulted phase to ground" newline ...
"%    LL / LLL       : Severity ohm between each pair of faulted phases (cross-coupling terms)" newline ...
"Y_f = zeros(3,3);" newline ...
"if fault_active && MechanismCode == 2" newline ...
"    g_f = frac / max(Severity, 1e-6);" newline ...
"    if FaultG > 0.5" newline ...
"        for k = 1:3" newline ...
"            if flt(k), Y_f(k,k) = g_f; end" newline ...
"        end" newline ...
"    else" newline ...
"        for k = 1:3" newline ...
"            m = mod(k, 3) + 1;" newline ...
"            if flt(k) && flt(m)" newline ...
"                Y_f(k,k) = Y_f(k,k) + g_f; Y_f(m,m) = Y_f(m,m) + g_f;" newline ...
"                Y_f(k,m) = Y_f(k,m) - g_f; Y_f(m,k) = Y_f(m,k) - g_f;" newline ...
"            end" newline ...
"        end" newline ...
"    end" newline ...
"end" newline ...
"% 3. Terminal bus voltage. Load: I_new = c + a*Vt with c = I_s - a*R_load.*I_s and a = Ts/L." newline ...
"%    Line (source side): W*I_line = Vs - Vt + Lr*I_src, with I_line = I_new + Y_f*Vt." newline ...
"%    => ((1 + W*a)*I + W*Y_f) * Vt = Vs - W*c + Lr*I_src" newline ...
"a_l = Ts / L;" newline ...
"c_vec = I_s - a_l * (R_load .* I_s);" newline ...
"M = (1 + W * a_l) * eye(3) + W * Y_f;" newline ...
"V_t = M \ (V_s - W * c_vec + Lr * I_src);" newline ...
"I_new = c_vec + a_l * V_t;" newline ...
"% 4. Open-circuit phases: load current decays, bus voltage is the source voltage (as in v6)" newline ...
"for k = 1:3" newline ...
"    if open_ph(k)" newline ...
"        I_new(k) = I_s(k) * exp(-Ts * (R_open + R_source) / L);" newline ...
"        V_t(k) = V_s(k);" newline ...
"    end" newline ...
"end" newline ...
"% 5. Measured line current = load current + fault current (CT upstream of the fault, downstream of the breaker)." newline ...
"%    Breaker open: ideal interruption, every current is zero, the bus shows the source voltage." newline ...
"if BreakerOpen > 0.5" newline ...
"    I_new = zeros(3,1); I_line = zeros(3,1); V_t = V_s;" newline ...
"else" newline ...
"    I_line = I_new + Y_f * V_t;" newline ...
"end" newline ...
"I_s = I_new; I_src = I_line;" newline ...
"Ia = I_line(1); Ib = I_line(2); Ic = I_line(3);" newline ...
"Va = V_t(1); Vb = V_t(2); Vc = V_t(3);" newline ...
"fault_flag = fault_active;" newline ...
"G = double(FaultG); A = double(FaultA); B = double(FaultB); C = double(FaultC);" newline ...
"tRec = FaultOnsetTime + FaultDuration + ReclosDelay;" newline ...
"reclose = double(t >= tRec && t < tRec + 1e-3);" newline ...
"end" newline ...
];
code = strjoin(code, '');
end

