function code = seq_3ph_body()
code = [ ...
"function [I1,I2,I0,Unbal2,Unbal0,UnbalV0] = seq_3ph(Ia,Ib,Ic,Va,Vb,Vc)" newline ...
"%#codegen" newline ...
"persistent buf idx n cosW sinW wsum I1ref V1ref" newline ...
"N = 200; WARMUP = 500; USE_HANN = true;" newline ...
"LAM = 1e-3; NORMAL_UNBAL = 0.02; NORMAL_STEP = 0.02;" newline ...
"if isempty(idx)" newline ...
"    buf = zeros(6,N); idx = 1; n = 0; I1ref = 0; V1ref = 0;" newline ...
"    j = 0:N-1; w = ones(1,N);" newline ...
"    if USE_HANN, w = 0.5 * (1 - cos(2*pi*j/N)); end" newline ...
"    cosW = cos(2*pi*j/N) .* w; sinW = -sin(2*pi*j/N) .* w; wsum = sum(w);" newline ...
"end" newline ...
"buf(:,idx) = [Ia; Ib; Ic; Va; Vb; Vc]; idx = mod(idx, N) + 1; n = n + 1;" newline ...
"ord = mod((0:N-1) + idx - 1, N) + 1;" newline ...
"bo = buf(:, ord);" newline ...
"re = bo * cosW.'; im = bo * sinW.';" newline ...
"P = complex(re, im) * (sqrt(2) / wsum);" newline ...
"a = complex(-0.5, sqrt(3)/2); a2 = conj(a);" newline ...
"p1 = (P(1) + a*P(2) + a2*P(3)) / 3;" newline ...
"p2 = (P(1) + a2*P(2) + a*P(3)) / 3;" newline ...
"p0 = (P(1) + P(2) + P(3)) / 3;" newline ...
"v1 = (P(4) + a*P(5) + a2*P(6)) / 3;" newline ...
"v0 = (P(4) + P(5) + P(6)) / 3;" newline ...
"I1 = abs(p1); I2 = abs(p2); I0 = abs(p0); V1 = abs(v1);" newline ...
"if n <= WARMUP" newline ...
"    I1ref = I1; V1ref = V1;" newline ...
"else" newline ...
"    normalUnbal = (I2 / max(I1ref, 1e-6) < NORMAL_UNBAL) && (I0 / max(I1ref, 1e-6) < NORMAL_UNBAL);" newline ...
"    if normalUnbal && abs(I1 - I1ref) <= NORMAL_STEP * I1ref" newline ...
"        I1ref = I1ref + LAM * (I1 - I1ref);" newline ...
"    end" newline ...
"    if normalUnbal && abs(V1 - V1ref) <= NORMAL_STEP * V1ref" newline ...
"        V1ref = V1ref + LAM * (V1 - V1ref);" newline ...
"    end" newline ...
"end" newline ...
"Unbal2 = I2 / max(I1ref, 1e-6);" newline ...
"Unbal0 = I0 / max(I1ref, 1e-6);" newline ...
"UnbalV0 = abs(v0) / max(V1ref, 1e-6);" newline ...
];
code = strjoin(code, '');
end

function code = detection_3ph_body()
code = [ ...
"function [cusum_flag_agg,obs_flag_agg,overcurrent_flag_agg,Cusum_A,Cusum_B,Cusum_C,Residual_A,Residual_B,Residual_C,Mu0_A,Mu0_B,Mu0_C,Cusum_U2,Cusum_U0,Cusum_V0] = detection_3ph(Va,Vb,Vc,Ia,Ib,Ic,Irms_A,Irms_B,Irms_C,Unbal2,Unbal0,UnbalV0,BreakerOpen)" newline ...
"    persistent mu0 var0 g_pos g_neg initialized sampleCount WARMUP_SAMPLES SETTLE_SAMPLES settleCount blank" newline ...
"    if isempty(initialized)" newline ...
"        mu0 = zeros(6,1); var0 = [0.01; 0.01; 0.01; 1e-6; 1e-6; 1e-6];" newline ...
"        g_pos = zeros(6,1); g_neg = zeros(6,1); initialized = true;" newline ...
"        sampleCount = 0; WARMUP_SAMPLES = 500; SETTLE_SAMPLES = 400; settleCount = 0; blank = 0;" newline ...
"    end" newline ...
"    sampleCount = sampleCount + 1;" newline ...
"    HOLD_SAMPLES = 500;   % 50 ms hold after the breaker closes again (lets the 200-sample windows refill)" newline ...
"    CUSUM_CAP = 10;       % anti-windup: CUSUM statistic is capped at CUSUM_CAP * H_THRESH" newline ...
"    if BreakerOpen > 0.5" newline ...
"        blank = HOLD_SAMPLES;" newline ...
"    elseif blank > 0" newline ...
"        blank = blank - 1;" newline ...
"    end" newline ...
"    hold_det = blank > 0;" newline ...
"    % 6 Channels: Irms A, B, C | Unbal2 | Unbal0 | UnbalV0 (the last three are dimensionless)" newline ...
"    x = [Irms_A; Irms_B; Irms_C; Unbal2; Unbal0; UnbalV0];" newline ...
"    err = x - mu0; residual = abs(err);" newline ...
"    % Minimum noise floor: 0.05 A for Irms, 0.005 (0.5 percent of the healthy reference) for the unbalance channels" newline ...
"    NOISE_FLOOR = [0.05; 0.05; 0.05; 0.005; 0.005; 0.005];" newline ...
"    std0 = max(sqrt(var0), NOISE_FLOOR);" newline ...
"    k = 1.0 * std0; H_THRESH = 10 * std0; OVERCURRENT_THRESH = mu0 + 15 * std0;" newline ...
"    if sampleCount <= WARMUP_SAMPLES" newline ...
"        if sampleCount > SETTLE_SAMPLES" newline ...
"            settleCount = settleCount + 1; delta = x - mu0;" newline ...
"            mu0 = mu0 + delta / settleCount; var0 = var0 + (delta .* (x - mu0) - var0) / settleCount;" newline ...
"        end" newline ...
"        g_pos = zeros(6,1); g_neg = zeros(6,1); cusum_stat = zeros(6,1);" newline ...
"        cusum_flag_ph = false(6,1); obs_flag_ph = false(6,1); overcurrent_flag_ph = false(6,1);" newline ...
"    elseif hold_det" newline ...
"        % Breaker open (or just closed): statistics held at zero, no flags, mu0 / var0 frozen" newline ...
"        g_pos = zeros(6,1); g_neg = zeros(6,1); cusum_stat = zeros(6,1);" newline ...
"        cusum_flag_ph = false(6,1); obs_flag_ph = false(6,1); overcurrent_flag_ph = false(6,1);" newline ...
"    else" newline ...
"        g_pos = min(max(0, g_pos + err - k), CUSUM_CAP * H_THRESH); g_neg = min(max(0, g_neg - err - k), CUSUM_CAP * H_THRESH);" newline ...
"        cusum_stat = max(g_pos, g_neg); cusum_flag_ph = cusum_stat > H_THRESH;" newline ...
"        obs_flag_ph = residual > 5 * std0; overcurrent_flag_ph = x > OVERCURRENT_THRESH;" newline ...
"        overcurrent_flag_ph(4:6) = false;   % Upper limit disabled for the unbalance channels" newline ...
"        normal_mask = ~(cusum_flag_ph | obs_flag_ph | overcurrent_flag_ph);" newline ...
"        delta_norm = x(normal_mask) - mu0(normal_mask);" newline ...
"        mu0(normal_mask) = 0.999 * mu0(normal_mask) + 0.001 * x(normal_mask);" newline ...
"        var0(normal_mask) = 0.999 * var0(normal_mask) + 0.001 * (delta_norm.^2);" newline ...
"    end" newline ...
"    cusum_flag_agg = any(cusum_flag_ph); obs_flag_agg = any(obs_flag_ph); overcurrent_flag_agg = any(overcurrent_flag_ph);" newline ...
"    Cusum_A = cusum_stat(1); Cusum_B = cusum_stat(2); Cusum_C = cusum_stat(3);" newline ...
"    Residual_A = residual(1); Residual_B = residual(2); Residual_C = residual(3);" newline ...
"    Mu0_A = mu0(1); Mu0_B = mu0(2); Mu0_C = mu0(3);" newline ...
"    Cusum_U2 = cusum_stat(4); Cusum_U0 = cusum_stat(5); Cusum_V0 = cusum_stat(6);" newline ...
"end" newline ...
];
code = strjoin(code, '');
end

function code = trip_latch_body()
