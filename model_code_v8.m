for k = 1:numel(fn)
    subsys = fn{k};
    if isfield(out_tags, subsys)
        tags = out_tags.(subsys); pos = positions.(subsys);
        for i = 1:length(tags)
            add_block('simulink/Signal Routing/Goto', [mdl '/' subsys '_Goto_' tags{i}], 'GotoTag', tags{i}, 'Position', [pos(3)+20, pos(2)+10+30*(i-1), pos(3)+120, pos(2)+30+30*(i-1)], 'ShowName', 'off');
