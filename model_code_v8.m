function code = breaker_3ph_body()
code = [ ...
"function [Ia_post,Ib_post,Ic_post,BreakerState_out,BreakerOpen_eff] = breaker_3ph(Ia,Ib,Ic,trip_cmd,reclose,FeedbackEnable,BreakerDelay)" newline ...
"%#codegen" newline ...
"persistent state tcnt" newline ...
"if isempty(state), state = 0; tcnt = 0; end" newline ...
"Ts = 1e-4;" newline ...
"delaySamples = round(BreakerDelay / Ts);" newline ...
"if reclose > 0.5" newline ...
"    state = 0; tcnt = 0;" newline ...
"else" newline ...
"    if trip_cmd > 0.5, tcnt = tcnt + 1; end" newline ...
"    if trip_cmd > 0.5 && tcnt > delaySamples, state = 1; end" newline ...
"end" newline ...
"Ia_post = Ia * (1 - state); Ib_post = Ib * (1 - state); Ic_post = Ic * (1 - state);" newline ...
"BreakerState_out = state;" newline ...
"% only this effective state is fed back to the plant and the detector; FeedbackEnable = 0 keeps the v6 behaviour" newline ...
"BreakerOpen_eff = state * double(FeedbackEnable > 0.5);" newline ...
"end" newline ...
];
code = strjoin(code, '');
end

function replace_matlab_function_code(blockPath, code)
    rt = sfroot; open_system(blockPath);
    blk = rt.find('-isa', 'Stateflow.EMChart', 'Path', blockPath);
    blk.Script = char(code);
end

function delete_block_ports(subsysPath)
    blks = find_system(subsysPath, 'SearchDepth', 1, 'BlockType', 'Inport');
    for i = 1:numel(blks), if ~strcmp(blks{i}, subsysPath), delete_block(blks{i}); end, end
    blks = find_system(subsysPath, 'SearchDepth', 1, 'BlockType', 'Outport');
    for i = 1:numel(blks), if ~strcmp(blks{i}, subsysPath), delete_block(blks{i}); end, end
end
