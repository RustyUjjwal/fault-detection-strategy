%% model_code_v8.m
%
% THREE-PHASE fault detection model (v8 = v7 + phase wrap + trip confirmation;
% v7 = v6 + source inductance + breaker feedback)
%
% WHAT CHANGED vs v6 (from the CSV analysis of fault_timeseries_all_1.csv):
%
% (b) SOURCE INDUCTANCE  [Sensing_ThreePhase / Fault_Injector, mask param SourceL, default 5 mH]
%     v6 had a purely resistive source (0.5 Ohm), so the fault current jumped to its final value
%     in one 0.1 ms step (Ia -29.8 A -> +159 A for LL_AB). The source is now Rs + Ls behind the
%     terminal bus (backward Euler, solved together with the bus voltage), so short-circuit
%     currents rise with a time constant of Ls / (Rs + Rfault) (about 5 ms for LG with the
%     defaults) and Phase / THD / Crest during faults become realistic.
%     SIDE EFFECTS you will see in the data (they are physics, not bugs):
%       - healthy Irms drops from 27.7 A to 24.1 A (extra 1.57 Ohm source reactance)
%       - bolted short-circuit currents are 2-3x lower than in v6 (LG_A I1 88 A -> 56 A)
%     Set SourceL = 0 to get v6 behaviour back (within 0.2 percent).
%
% (a) BREAKER FEEDBACK  [Breaker_Contactor_Plant_3ph + Sensing_ThreePhase]
%     The breaker now really opens the feeder. Trip command -> contacts open after BreakerDelay
%     (default 40 ms = 2 cycles; an ideal breaker with zero delay never lets the fault develop)
%     -> the injector forces all line currents to zero (ideal interruption: no arc, no decay).
%     The feedback goes through a Unit Delay at top level (BreakerOpen_Delay) to avoid an
%     algebraic loop. Mask parameters on Breaker_Contactor_Plant_3ph:
%         FeedbackEnable  1 = breaker acts on the plant, 0 = breaker only latches (v6 behaviour,
%                         use this to characterise the bolted fault: settled Irms, I1/I2/I0)
%         BreakerDelay    contact opening time after the trip command, seconds
%     After the fault window the injector emits a 1 ms reclose pulse (signal 'reclose') at
%     FaultOnsetTime + FaultDuration + ReclosDelay (mask param on Sensing_ThreePhase, default
%     0.1 s). The pulse resets the trip latch and closes the breaker.
%     Ia_post / Ib_post / Ic_post (current after the contacts) and reclose are now logged.
%
% DETECTOR CHANGES (needed once the current can stop):
%     - CUSUM anti-windup: g_pos / g_neg are capped at CUSUM_CAP * H_THRESH (10 x). In v6 the sum
%       grew to 2e6 and never came down.
%       NOTE: with that cap, max_cusum saturates at the cap for every fault, so it no longer
%       carries information. Use trip delay, let-through peak and I2t instead (dump script).
%     - Hold: while the effective breaker state is open, and for HOLD_SAMPLES (500 = 50 ms)
%       after it closes again, the CUSUM statistics are held at zero, mu0 / var0 are frozen and
%       no flags are raised. This lets the detector see the load come back after a reclose.
%     - The trip latch is now a MATLAB Function with a reclose reset input (Decision_Trip has
%       4 inputs: Cusum_agg, Obs_agg, Overcurrent_agg, reclose).
%
% UNCHANGED vs v6: Signal_Conditioning_3ph (seeded noise), Sequence_Components_3ph, all fault
% mechanisms and severity ranges. (The v6 header text mentions an R_GND_RETURN voltage shift;
% the v6 injector code does not contain it. LG / LL / LLG separation comes from the fault
% admittance matrix, i.e. from I0 and I2, and that is unchanged.)
%
% WHAT CHANGED vs v7 (from the v7 data analysis):
%     - Phase_A/B/C are wrapped to (-pi, pi]  [SigCond_3ph]. Before, angle(V) - angle(I) was not
%       wrapped: the same physical angle appeared as 2.282 or -4.001 rad depending on the phase.
%       Phase values in the CSV change accordingly.
%     - Trip confirmation  [Trip_Latch]: a detector flag must stay high for CONFIRM_SAMPLES
%       (50 samples = 5 ms, a quarter cycle) before the trip latch sets. Trip delays are now about
%       5 ms plus the detection time and no longer depend on the fault inception angle as strongly
%       (the old 0.2-4.6 ms spread was the detector reacting to a one-sample RMS step).
%       Set CONFIRM_SAMPLES = 1 in trip_latch_body() to get v7 behaviour back.
%       Side effect: let-through peak and I2t grow, because the fault runs about 5 ms longer
%       before the 40 ms breaker delay starts.
%
% KNOWN LIMITS (not changed here):
%     - Noise is added inside SigCond only, so Ia/Va (and the sequence / unbalance channels)
%       are noise free.
%     - LL/LLL Severity is ohms per pair, LG/LLG/LLLG is ohms per phase to ground, so LLL and
%       LLLG are not the same bolted fault (see analysis).
%
% USAGE:
% >> model_code_v8
% >> fault_timeseries_dump_v8

function model_code_v8()

mdl = 'fault_detection_system_v8';

if bdIsLoaded(mdl)
    close_system(mdl, 0);
end
if exist([mdl '.slx'], 'file')
    delete([mdl '.slx']);
end

new_system(mdl);
open_system(mdl);
set_param(mdl, 'Solver', 'FixedStepDiscrete', 'FixedStep', '1e-4', 'StopTime', '2');

%% =====================================================================
%% 1. SENSING_THREEPHASE - masked 3-phase RL plant + fault injection
%%    Inputs : BreakerOpen (delayed, from top level)
%%    Outputs: Ia Ib Ic Va Vb Vc fault_flag G A B C reclose
%% =====================================================================
sens = [mdl '/Sensing_ThreePhase'];
add_block('built-in/Subsystem', sens);
delete_block_ports(sens);

add_block('simulink/Sources/Sine Wave', [sens '/Va_source'], 'Amplitude', '325', 'Frequency', '314.159', 'Phase', '0', 'Position', [30 30 70 60]);
add_block('simulink/Sources/Sine Wave', [sens '/Vb_source'], 'Amplitude', '325', 'Frequency', '314.159', 'Phase', num2str(-2*pi/3), 'Position', [30 90 70 120]);
add_block('simulink/Sources/Sine Wave', [sens '/Vc_source'], 'Amplitude', '325', 'Frequency', '314.159', 'Phase', num2str(2*pi/3), 'Position', [30 150 70 180]);
add_block('simulink/Sources/Clock', [sens '/Clock1'], 'Position', [30 210 60 230]);
add_block('simulink/User-Defined Functions/MATLAB Function', [sens '/Fault_Injector'], 'Position', [150 30 320 330]);
replace_matlab_function_code([sens '/Fault_Injector'], fault_injector_body());

% Injector inputs: 1-3 source voltages, 4 time, 5-15 mask parameters, 16 breaker-open feedback
constParamNames = {'FaultG','FaultA','FaultB','FaultC','MechanismCode','Severity','RampDuration','FaultOnsetTime','FaultDuration','SourceL','ReclosDelay'};
for i = 1:numel(constParamNames)
    cblk = [sens '/' constParamNames{i} '_const'];
    add_block('simulink/Sources/Constant', cblk, 'Value', constParamNames{i}, 'Position', [60 360+30*(i-1) 100 380+30*(i-1)]);
    add_line(sens, [constParamNames{i} '_const/1'], sprintf('Fault_Injector/%d', 4+i), 'autorouting', 'on');
end
add_block('simulink/Sources/In1', [sens '/BreakerOpen_in'], 'Port', '1', 'Position', [30 700 60 720]);
add_line(sens, 'BreakerOpen_in/1', 'Fault_Injector/16', 'autorouting', 'on');

outPortNames = {'Ia_out','Ib_out','Ic_out','Va_out','Vb_out','Vc_out','FaultFlag_out','G_out','A_out','B_out','C_out','Reclose_out'};
for i = 1:numel(outPortNames)
    add_block('simulink/Ports & Subsystems/Out1', [sens '/' outPortNames{i}], 'Position', [400 30*(i)-10 430 30*(i)+10], 'Port', num2str(i));
end

add_line(sens, 'Va_source/1', 'Fault_Injector/1', 'autorouting', 'on');
add_line(sens, 'Vb_source/1', 'Fault_Injector/2', 'autorouting', 'on');
add_line(sens, 'Vc_source/1', 'Fault_Injector/3', 'autorouting', 'on');
add_line(sens, 'Clock1/1', 'Fault_Injector/4', 'autorouting', 'on');
for i = 1:numel(outPortNames)
    add_line(sens, ['Fault_Injector/' num2str(i)], sprintf('%s/1', outPortNames{i}), 'autorouting', 'on');
end

maskObj = Simulink.Mask.create(sens);
maskObj.addParameter('Type', 'checkbox', 'Prompt', 'Ground involved (G)', 'Name', 'FaultG', 'Value', 'off');
maskObj.addParameter('Type', 'checkbox', 'Prompt', 'Phase A involved', 'Name', 'FaultA', 'Value', 'off');
maskObj.addParameter('Type', 'checkbox', 'Prompt', 'Phase B involved', 'Name', 'FaultB', 'Value', 'off');
maskObj.addParameter('Type', 'checkbox', 'Prompt', 'Phase C involved', 'Name', 'FaultC', 'Value', 'off');
maskObj.addParameter('Type', 'edit', 'Prompt', 'Mechanism code', 'Name', 'MechanismCode', 'Value', '2', 'Evaluate', 'on');
maskObj.addParameter('Type', 'edit', 'Prompt', 'Severity', 'Name', 'Severity', 'Value', '0.5', 'Evaluate', 'on');
maskObj.addParameter('Type', 'edit', 'Prompt', 'Ramp duration (s)', 'Name', 'RampDuration', 'Value', '0', 'Evaluate', 'on');
maskObj.addParameter('Type', 'edit', 'Prompt', 'Fault onset time (s)', 'Name', 'FaultOnsetTime', 'Value', '0.4', 'Evaluate', 'on');
maskObj.addParameter('Type', 'edit', 'Prompt', 'Fault duration (s)', 'Name', 'FaultDuration', 'Value', '1.0', 'Evaluate', 'on');
maskObj.addParameter('Type', 'edit', 'Prompt', 'Source inductance (H), 0 = v6 behaviour', 'Name', 'SourceL', 'Value', '5e-3', 'Evaluate', 'on');
maskObj.addParameter('Type', 'edit', 'Prompt', 'Reclose delay after clearance (s)', 'Name', 'ReclosDelay', 'Value', '0.1', 'Evaluate', 'on');
set_param(sens, 'FaultG', 'off', 'FaultA', 'off', 'FaultB', 'off', 'FaultC', 'off', 'MechanismCode', '2', 'Severity', '0.5', 'RampDuration', '0', 'FaultOnsetTime', '0.4', 'FaultDuration', '1.0', 'SourceL', '5e-3', 'ReclosDelay', '0.1');

%% =====================================================================
%% 2. SIGNAL_CONDITIONING_3PH (unchanged from v6)
%% =====================================================================
sc = [mdl '/Signal_Conditioning_3ph'];
add_block('built-in/Subsystem', sc);
delete_block_ports(sc);
for i = 1:6
    blk = [sc '/In' num2str(i)];
    add_block('simulink/Sources/In1', blk, 'Position', [30 30+40*(i-1) 60 50+40*(i-1)]);
    set_param(blk, 'Port', num2str(i));
end
add_block('simulink/User-Defined Functions/MATLAB Function', [sc '/SigCond_3ph'], 'Position', [150 30 380 260]);
replace_matlab_function_code([sc '/SigCond_3ph'], sigcond_3ph_body());
outNames = {'Irms_A','Irms_B','Irms_C','Crest_A','Crest_B','Crest_C','THD_A','THD_B','THD_C','Phase_A','Phase_B','Phase_C'};
for i = 1:numel(outNames)
    blk = [sc '/' outNames{i}];
    add_block('simulink/Ports & Subsystems/Out1', blk, 'Position', [420 20+30*(i-1) 450 40+30*(i-1)], 'Port', num2str(i));
    add_line(sc, ['SigCond_3ph/' num2str(i)], [outNames{i} '/1'], 'autorouting', 'on');
end
for i = 1:6
    add_line(sc, ['In' num2str(i) '/1'], ['SigCond_3ph/' num2str(i)], 'autorouting', 'on');
end
add_block('simulink/Sources/Constant', [sc '/NoiseSeed_const'], 'Value', 'NoiseSeed', 'Position', [60 290 100 310]);
add_line(sc, 'NoiseSeed_const/1', 'SigCond_3ph/7', 'autorouting', 'on');
scMask = Simulink.Mask.create(sc);
scMask.addParameter('Type', 'edit', 'Prompt', 'Noise seed', 'Name', 'NoiseSeed', 'Value', '0', 'Evaluate', 'on');
set_param(sc, 'NoiseSeed', '0');

%% =====================================================================
%% 3. SEQUENCE_COMPONENTS_3PH (unchanged from v6)
%% =====================================================================
sq = [mdl '/Sequence_Components_3ph'];
add_block('built-in/Subsystem', sq);
delete_block_ports(sq);
for i = 1:6
    blk = [sq '/In' num2str(i)];
    add_block('simulink/Sources/In1', blk, 'Position', [30 30+40*(i-1) 60 50+40*(i-1)]);
    set_param(blk, 'Port', num2str(i));
end
add_block('simulink/User-Defined Functions/MATLAB Function', [sq '/Seq_3ph'], 'Position', [150 30 360 260]);
replace_matlab_function_code([sq '/Seq_3ph'], seq_3ph_body());
outNamesS = {'I1_seq','I2_seq','I0_seq','Unbal2','Unbal0','UnbalV0'};
for i = 1:numel(outNamesS)
    blk = [sq '/' outNamesS{i}];
    add_block('simulink/Ports & Subsystems/Out1', blk, 'Position', [400 20+30*(i-1) 430 40+30*(i-1)], 'Port', num2str(i));
    add_line(sq, ['Seq_3ph/' num2str(i)], [outNamesS{i} '/1'], 'autorouting', 'on');
end
for i = 1:6
    add_line(sq, ['In' num2str(i) '/1'], ['Seq_3ph/' num2str(i)], 'autorouting', 'on');
end

%% =====================================================================
%% 4. DETECTION_LAYER_3PH (13 inputs: 12 as in v6 + delayed breaker-open state)
%% =====================================================================
dl = [mdl '/Detection_Layer_3ph'];
add_block('built-in/Subsystem', dl);
delete_block_ports(dl);
for i = 1:13
    blk = [dl '/In' num2str(i)];
    add_block('simulink/Sources/In1', blk, 'Position', [30 20+30*(i-1) 60 40+30*(i-1)]);
    set_param(blk, 'Port', num2str(i));
end
add_block('simulink/User-Defined Functions/MATLAB Function', [dl '/Detection_3ph'], 'Position', [150 20 420 400]);
replace_matlab_function_code([dl '/Detection_3ph'], detection_3ph_body());

outNames2 = {'CusumFlag_agg','ObsFlag_agg','OvercurrentFlag_agg', 'Cusum_A','Cusum_B','Cusum_C','Residual_A','Residual_B','Residual_C', 'Mu0_A','Mu0_B','Mu0_C','Cusum_U2','Cusum_U0','Cusum_V0'};
for i = 1:numel(outNames2)
    blk = [dl '/' outNames2{i}];
    add_block('simulink/Ports & Subsystems/Out1', blk, 'Position', [460 10+27*(i-1) 490 30+27*(i-1)], 'Port', num2str(i));
    add_line(dl, ['Detection_3ph/' num2str(i)], [outNames2{i} '/1'], 'autorouting', 'on');
end
for i = 1:13
    add_line(dl, ['In' num2str(i) '/1'], ['Detection_3ph/' num2str(i)], 'autorouting', 'on');
end

%% =====================================================================
%% 5. DECISION_TRIP (latch with reclose reset)
%% =====================================================================
dt = [mdl '/Decision_Trip'];
add_block('built-in/Subsystem', dt);
delete_block_ports(dt);
for i = 1:4
    blk = [dt '/In' num2str(i)];
    add_block('simulink/Sources/In1', blk, 'Position', [30 30+40*(i-1) 60 50+40*(i-1)]);
    set_param(blk, 'Port', num2str(i));
end
add_block('simulink/User-Defined Functions/MATLAB Function', [dt '/Trip_Latch'], 'Position', [150 30 320 190]);
replace_matlab_function_code([dt '/Trip_Latch'], trip_latch_body());
add_block('simulink/Ports & Subsystems/Out1', [dt '/Trip_out'], 'Position', [360 100 390 120], 'Port', '1');
for i = 1:4
    add_line(dt, ['In' num2str(i) '/1'], ['Trip_Latch/' num2str(i)], 'autorouting', 'on');
end
add_line(dt, 'Trip_Latch/1', 'Trip_out/1', 'autorouting', 'on');

%% =====================================================================
%% 6. BREAKER_CONTACTOR_PLANT_3PH
%%    Inputs : Ia Ib Ic trip reclose
%%    Outputs: Ia_post Ib_post Ic_post BreakerState_out BreakerOpen_eff
%% =====================================================================
bp = [mdl '/Breaker_Contactor_Plant_3ph'];
add_block('built-in/Subsystem', bp);
delete_block_ports(bp);
for i = 1:5
    blk = [bp '/In' num2str(i)];
    add_block('simulink/Sources/In1', blk, 'Position', [30 30+40*(i-1) 60 50+40*(i-1)]);
    set_param(blk, 'Port', num2str(i));
end
add_block('simulink/User-Defined Functions/MATLAB Function', [bp '/Breaker_3ph'], 'Position', [150 30 320 260]);
replace_matlab_function_code([bp '/Breaker_3ph'], breaker_3ph_body());
outNamesB = {'Ia_post','Ib_post','Ic_post','BreakerState_out','BreakerOpen_eff'};
for i = 1:numel(outNamesB)
    blk = [bp '/' outNamesB{i}];
    add_block('simulink/Ports & Subsystems/Out1', blk, 'Position', [360 20+35*(i-1) 390 40+35*(i-1)], 'Port', num2str(i));
    add_line(bp, ['Breaker_3ph/' num2str(i)], [outNamesB{i} '/1'], 'autorouting', 'on');
end
for i = 1:5
    add_line(bp, ['In' num2str(i) '/1'], ['Breaker_3ph/' num2str(i)], 'autorouting', 'on');
end
add_block('simulink/Sources/Constant', [bp '/FeedbackEnable_const'], 'Value', 'FeedbackEnable', 'Position', [60 260 100 280]);
add_block('simulink/Sources/Constant', [bp '/BreakerDelay_const'], 'Value', 'BreakerDelay', 'Position', [60 300 100 320]);
add_line(bp, 'FeedbackEnable_const/1', 'Breaker_3ph/6', 'autorouting', 'on');
add_line(bp, 'BreakerDelay_const/1', 'Breaker_3ph/7', 'autorouting', 'on');
bpMask = Simulink.Mask.create(bp);
bpMask.addParameter('Type', 'edit', 'Prompt', 'Feedback enable (1 = breaker interrupts the plant, 0 = latch only)', 'Name', 'FeedbackEnable', 'Value', '1', 'Evaluate', 'on');
bpMask.addParameter('Type', 'edit', 'Prompt', 'Breaker opening delay after trip command (s)', 'Name', 'BreakerDelay', 'Value', '0.04', 'Evaluate', 'on');
set_param(bp, 'FeedbackEnable', '1', 'BreakerDelay', '0.04');

%% =====================================================================
%% 7. LOGGING_SCOPES_3PH - To Workspace for every channel + grouped scopes
%% =====================================================================
lg = [mdl '/Logging_Scopes_3ph'];
add_block('built-in/Subsystem', lg);
delete_block_ports(lg);

logSignals = [ ...
    {'Ia','Ib','Ic','Va','Vb','Vc'}, ...                                                                              % 1-6
    {'Irms_A','Irms_B','Irms_C','Crest_A','Crest_B','Crest_C','THD_A','THD_B','THD_C','Phase_A','Phase_B','Phase_C'}, ... % 7-18
    {'Cusum_A','Cusum_B','Cusum_C','Residual_A','Residual_B','Residual_C','Mu0_A','Mu0_B','Mu0_C'}, ...               % 19-27
    {'trip','breaker_state','fault_flag','G','A','B','C'}, ...                                                         % 28-34
    {'I1_seq','I2_seq','I0_seq','Unbal2','Unbal0','UnbalV0','Cusum_U2','Cusum_U0','Cusum_V0'}, ...                    % 35-43
    {'Ia_post','Ib_post','Ic_post','reclose'} ];                                                                       % 44-47

for i = 1:numel(logSignals)
    add_block('simulink/Sources/In1', [lg '/' logSignals{i} '_in'], 'Position', [30 20+30*(i-1) 60 40+30*(i-1)], 'Port', num2str(i));
    add_block('simulink/Sinks/To Workspace', [lg '/log_' logSignals{i}], 'Position', [150 20+30*(i-1) 230 40+30*(i-1)], 'VariableName', ['log_' logSignals{i}], 'SaveFormat', 'Timeseries');
    add_line(lg, [logSignals{i} '_in/1'], ['log_' logSignals{i} '/1'], 'autorouting', 'on');
end

scopeGroups = struct( ...
    'name',    {'Ia_Ib_Ic','Va_Vb_Vc','Irms','Crest','THD','Phase','Cusum','Residual','Mu0','Trip_Breaker_Fault','GABC','Sequence','Cusum_Unbal','Breaker_Plant'}, ...
    'indices', {1:3, 4:6, 7:9, 10:12, 13:15, 16:18, 19:21, 22:24, 25:27, 28:30, 31:34, 35:40, 41:43, 44:47});
for gi = 1:numel(scopeGroups)
    idxRange = scopeGroups(gi).indices;
    n = numel(idxRange);
    scopeName = ['Scope_' scopeGroups(gi).name];
    yTop = 20 + 30*(idxRange(1)-1);
    add_block('simulink/Sinks/Scope', [lg '/' scopeName], ...
        'Position', [320 yTop 380 yTop + max(40, 25*n)], 'NumInputPorts', num2str(n));
    for j = 1:n
        add_line(lg, [logSignals{idxRange(j)} '_in/1'], sprintf('%s/%d', scopeName, j), 'autorouting', 'on');
    end
end

%% =====================================================================
%% TOP-LEVEL WIRING (Goto / From blocks)
%% =====================================================================
positions = struct( ...
    'Sensing_ThreePhase', [150 40 350 420], ...
    'Signal_Conditioning_3ph', [600 40 800 420], ...
    'Sequence_Components_3ph', [150 700 350 880], ...
    'Detection_Layer_3ph', [1050 40 1250 420], ...
    'Decision_Trip', [1500 60 1640 180], ...
    'Breaker_Contactor_Plant_3ph', [150 480 350 650], ...
    'Logging_Scopes_3ph', [600 480 840 1700]);
fn = fieldnames(positions);
for k = 1:numel(fn)
    set_param([mdl '/' fn{k}], 'Position', positions.(fn{k}));
end

out_tags = struct();
out_tags.Sensing_ThreePhase = {'Ia', 'Ib', 'Ic', 'Va', 'Vb', 'Vc', 'fault_flag', 'G', 'A', 'B', 'C', 'reclose'};
out_tags.Signal_Conditioning_3ph = {'Irms_A','Irms_B','Irms_C','Crest_A','Crest_B','Crest_C','THD_A','THD_B','THD_C','Phase_A','Phase_B','Phase_C'};
